/**
 * Hydra Theme Editor — visual theme engine.
 *
 * The engine deliberately generates ordinary CSS so it works with Hydra's
 * existing custom-theme pipeline (theme.code + injectCustomCss), without
 * requiring changes to Hydra's source renderer.
 */

export type EditorState =
  | "normal"
  | "hover"
  | "active"
  | "focus"
  | "disabled"
  | "selected";

export type LayerKind = "background" | "overlay" | "texture" | "decoration";

export interface VisualTarget {
  id: string;
  label: string;
  selector: string;
  category: string;
  description?: string;
  states?: EditorState[];
}

export interface TargetStyle {
  color?: string;
  backgroundColor?: string;
  backgroundImage?: string;
  backgroundSize?: string;
  backgroundPosition?: string;
  backgroundRepeat?: string;
  opacity?: number;
  borderColor?: string;
  borderWidth?: number;
  boxShadow?: string;
  fontSize?: number;
  fontWeight?: number;
  letterSpacing?: number;
  padding?: string;
  margin?: string;
  gap?: number;
  transform?: string;
  transition?: string;
  backdropFilter?: string;
  filter?: string;
  fontFamily?: string;
  fontStyle?: string;
  lineHeight?: string;
  textTransform?: string;
  borderStyle?: string;
  borderRadius?: number;
  zIndex?: number;
  customProperties?: Record<string, string>;
}

export interface VisualRule {
  targetId: string;
  state: EditorState;
  style: TargetStyle;
}

export interface VisualLayer {
  id: string;
  name: string;
  kind: LayerKind;
  targetId: string;
  image: string;
  opacity: number;
  size: string;
  position: string;
  repeat: string;
  blendMode: string;
  enabled: boolean;
}

export interface EditorDocument {
  rules: VisualRule[];
  layers: VisualLayer[];
  variables?: Record<string, string>;
  conditions?: string[];
  discoveredTargets?: VisualTarget[];
}

